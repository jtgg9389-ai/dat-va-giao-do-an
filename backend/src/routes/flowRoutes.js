const express = require('express');
const mongoose = require('mongoose');
const c = require('../controllers/flowController');
const { verifyToken, requireRole } = require('../middleware/authMiddleware');
const router = express.Router();
router.use(verifyToken);
router.param('id', (req, res, next, id) => mongoose.isValidObjectId(id) ? next() : res.status(404).json({ message: 'ID không hợp lệ' }));
router.get('/orders', requireRole('customer'), c.myOrders);
router.get('/orders/:id', c.orderDetail);
router.post('/orders/:id/cancel', requireRole('customer'), c.cancel);
router.post('/orders/:id/mock-payment', requireRole('customer'), c.mockPayment);
router.post('/orders/:id/review', requireRole('customer'), c.review);
router.get('/restaurants/:id/reviews', c.restaurantReviews);
router.get('/notifications', c.notifications);
router.post('/notifications/:id/read', c.readNotification);
router.get('/driver/profile', requireRole('driver'), c.driverProfile);
router.put('/driver/availability', requireRole('driver'), c.availability);
router.post('/driver/location', requireRole('driver'), c.location);
router.post('/driver/offers/:id', requireRole('driver'), c.offer);
router.patch('/driver/jobs/:id/status', requireRole('driver'), c.driverStatus);
router.post('/driver/jobs/:id/issue', requireRole('driver'), c.issue);
router.get('/driver/earnings', requireRole('driver'), c.earnings);
router.get('/settlements', requireRole('restaurant', 'driver', 'admin'), c.settlements);
router.get('/admin/drivers', requireRole('admin'), c.drivers);
router.patch('/admin/drivers/:id/review', requireRole('admin'), c.reviewDriver);
router.get('/admin/orders', requireRole('admin'), c.adminOrders);
router.post('/admin/orders/:id/action', requireRole('admin'), c.adminAction);
router.post('/admin/settlements/finalize', requireRole('admin'), c.finalize);
router.post('/admin/settlements/:id/transfer', requireRole('admin'), c.transfer);
router.post('/admin/settlements/:id/adjustments', requireRole('admin'), c.adjust);
router.post('/admin/adjustments/:id/transfer', requireRole('admin'), c.payAdjustment);
router.get('/admin/reports', requireRole('admin'), c.adminReport);
module.exports = router;
